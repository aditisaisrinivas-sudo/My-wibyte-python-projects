import turtle
t = turtle.Turtle()
t.shape('triangle')

t.penup()
t.fillcolor("yellow")
t.pencolor("black")
t.pensize(4)
t.begin_fill()
t.goto(-100,100)
t.pendown()
t.goto(100,100)
t.goto(100,-100)
t.goto(-100,-100)
t.goto(-100,100)
t.end_fill()

t.penup()
t.goto(0,30)
t.pensize(1)
t.pendown()
t.fillcolor("white")
t.setheading(90)
t.begin_fill()
t.circle(25)
t.circle(-25)
t.end_fill()

t.penup()
t.goto(-15,30)
t.dot(20,"blue")
t.goto(15,30)
t.dot(20,"blue")
t.end_fill()


t.penup()
t.goto(35,-20)
t.pencolor("black")
t.pensize(4)
t.pendown()
t.goto(-35,-20)
t.penup()


t.goto(-5,-20)
t.fillcolor("white")
t.pensize(1)
t.pencolor("black")

t.begin_fill()
t.pendown()
t.goto(-5,-40)
t.goto(5,-40)
t.goto(5,-20)
t.goto(-5,-20)
t.end_fill()
t.penup()

t.penup()
t.goto(-60,100)
t.setheading(50)

t.pencolor("black")
t.fillcolor("red")
t.pensize(2)

t.begin_fill()
t.pendown()
t.circle(-60,100)
t.goto(-60,100)
t.end_fill()

t.hideturtle()
turtle.mainloop()
